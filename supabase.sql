
CREATE TABLE IF NOT EXISTS public.guestbook (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.guestbook ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON public.guestbook TO anon, authenticated;

GRANT USAGE, SELECT ON SEQUENCE public.guestbook_id_seq
TO anon, authenticated;

CREATE POLICY "Anyone can read guestbook"
ON public.guestbook
FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Anyone can add guestbook message"
ON public.guestbook
FOR INSERT
TO anon, authenticated
WITH CHECK (
  char_length(name) BETWEEN 1 AND 60
  AND char_length(message) BETWEEN 1 AND 500
);
